#!/usr/bin/env bash
# A throwaway Jellyfin server for manual and end-to-end testing of the port.
#
#   scripts/test-server.sh up      start (or reuse) the server and seed it; prints its URL
#   scripts/test-server.sh down    stop and remove the container (data is kept)
#   scripts/test-server.sh reset   down + delete its data
#   scripts/test-server.sh url     print the URL
#
# One server is shared by every checkout on this machine. Seeded state: the startup wizard is
# completed with the administrator below, and libraries (Movies: 4 movies, one with two audio
# tracks and an external subtitle, one in VP9/Opus; Shows: "Test Show" with 4 episodes in 2 seasons;
# Music: 2 artists, 2 albums, 4 songs; Photos and Books for the managed-player tests) hold synthetic
# media generated by seed-media.sh and seed-players.sh.
# Data lives on disk under the port's cache directory.
set -euo pipefail

# JELLYFIN_INSTANCE=<name> (with its own JELLYFIN_PORT) selects a private server with the same seed
# for tests that change the server itself (libraries, plugins, tuners, network settings):
#   JELLYFIN_INSTANCE=livetv JELLYFIN_PORT=18098 scripts/test-server.sh up|down|reset
INSTANCE="${JELLYFIN_INSTANCE:-}"
if [ -n "$INSTANCE" ] && [ -z "${JELLYFIN_PORT:-}" ]; then
    echo "JELLYFIN_INSTANCE needs its own JELLYFIN_PORT" >&2; exit 2
fi
NAME="jellyfin-web-blazor-testserver${INSTANCE:+-$INSTANCE}"
IMAGE="${JELLYFIN_IMAGE:-jellyfin/jellyfin:12.4.20261026-211555}"
PORT="${JELLYFIN_PORT:-18096}"
DATA="${JFWEB_CACHE:-$HOME/.cache/jellyfin-web-blazor}/testserver${INSTANCE:+-$INSTANCE}"
URL="http://localhost:$PORT"
export TEST_USER="${TEST_USER:-admin}" TEST_PASSWORD="${TEST_PASSWORD:-jellyfin}"
AUTH='MediaBrowser Client="seed", Device="seed", DeviceId="seed", Version="1"'

api() { # api METHOD PATH [JSON]
    curl -fsS -X "$1" "$URL$2" -H "Authorization: $AUTH" -H 'Content-Type: application/json' ${3:+-d "$3"}
}

up() {
    if ! docker ps --format '{{.Names}}' | grep -qx "$NAME"; then
        docker rm -f "$NAME" >/dev/null 2>&1 || true
        mkdir -p "$DATA/config" "$DATA/cache" "$DATA/media/movies" "$DATA/media/shows" "$DATA/media/music"
        docker run -d --name "$NAME" --user "$(id -u):$(id -g)" -p "$PORT:8096" --memory 1g \
            -v "$DATA/config:/config" -v "$DATA/cache:/cache" -v "$DATA/media:/media:ro" "$IMAGE" >/dev/null
    fi
    for _ in $(seq 1 90); do
        # While it migrates its database the server answers without the wizard state.
        if curl -fsS "$URL/System/Info/Public" 2>/dev/null | grep -q '"StartupWizardCompleted"'; then break; fi
        sleep 2
    done
    if curl -fsS "$URL/System/Info/Public" | grep -q '"StartupWizardCompleted":false'; then
        api POST /Startup/Configuration '{"UICulture":"en-US","MetadataCountryCode":"US","PreferredMetadataLanguage":"en"}'
        api GET /Startup/User >/dev/null
        api POST /Startup/User "{\"Name\":\"$TEST_USER\",\"Password\":\"$TEST_PASSWORD\"}"
        api POST /Startup/RemoteAccess '{"EnableRemoteAccess":true,"EnableAutomaticPortMapping":false}'
        api POST /Startup/Complete
    fi
    seed_libraries
    echo "$URL (user: $TEST_USER, password: $TEST_PASSWORD)"
}

# Creates the Movies / Shows / Music libraries over the generated media (once) and waits for the scan.
seed_libraries() {
    "$(dirname "${BASH_SOURCE[0]}")/seed-media.sh" "$DATA/media" "$IMAGE"
    "$(dirname "${BASH_SOURCE[0]}")/seed-players.sh" "$DATA/media" "$IMAGE"
    local token
    token="$(api POST /Users/AuthenticateByName "{\"Username\":\"$TEST_USER\",\"Pw\":\"$TEST_PASSWORD\"}" \
        | sed -E 's/.*"AccessToken":"([^"]+)".*/\1/')"
    authed() { curl -fsS -X "$1" "$URL$2" -H "Authorization: $AUTH, Token=\"$token\"" -H 'Content-Type: application/json' ${3:+-d "$3"}; }
    # No remote metadata or image providers: the server must not depend on the internet. Each
    # library is checked independently so a server seeded before the player fixtures were added
    # gets the new Photos/Books libraries without duplicating its existing libraries.
    local types='[{"Type":"Movie","MetadataFetchers":[],"ImageFetchers":[]},{"Type":"Series","MetadataFetchers":[],"ImageFetchers":[]},{"Type":"Season","MetadataFetchers":[],"ImageFetchers":[]},{"Type":"Episode","MetadataFetchers":[],"ImageFetchers":[]},{"Type":"MusicAlbum","MetadataFetchers":[],"ImageFetchers":[]},{"Type":"MusicArtist","MetadataFetchers":[],"ImageFetchers":[]},{"Type":"Audio","MetadataFetchers":[],"ImageFetchers":[]},{"Type":"Photo","MetadataFetchers":[],"ImageFetchers":[]},{"Type":"Book","MetadataFetchers":[],"ImageFetchers":[]}]'
    local lib
    for lib in "Movies:movies:movies" "Shows:tvshows:shows" "Music:music:music" "Photos:homevideos:photos" "Books:books:books"; do
        IFS=: read -r name type dir <<< "$lib"
        if ! authed GET /Library/VirtualFolders | grep -q "\"Name\":\"$name\""; then
            authed POST "/Library/VirtualFolders?name=$name&collectionType=$type&refreshLibrary=false" \
                "{\"LibraryOptions\":{\"Enabled\":true,\"EnableRealtimeMonitor\":false,\"PathInfos\":[{\"Path\":\"/media/$dir\"}],\"TypeOptions\":$types}}"
        fi
    done
    scanned() { authed GET '/Items?Recursive=true&IncludeItemTypes=Movie,Episode,Audio&Limit=0' | grep -q '"TotalRecordCount":12'; }
    players_scanned() { authed GET '/Items?Recursive=true&IncludeItemTypes=Photo,Book&Limit=1' | grep -q '"TotalRecordCount":[1-9]'; }
    scanned && players_scanned && return 0
    authed POST /Library/Refresh
    for _ in $(seq 1 90); do
        if scanned && players_scanned; then return 0; fi
        sleep 2
    done
    echo "warning: the media scan has not finished (expected media and player fixtures)" >&2
}

case "${1:-up}" in
    up) up ;;
    down) docker rm -f "$NAME" >/dev/null 2>&1 || true ;;
    reset) docker rm -f "$NAME" >/dev/null 2>&1 || true; rm -rf "$DATA" ;;
    url) echo "$URL" ;;
    *) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//' ;;
esac
